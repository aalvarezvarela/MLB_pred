"""Schema versions for generated MLB training datasets.

Increment this value whenever a regenerated CSV gains, loses, or redefines a
column. Versioned filenames keep older, checksum-pinned datasets intact.

History
-------
``1_0``
    First one-row-per-game dataset. Carries pregame features plus reproducible
    outcomes for total runs, home margin, total-line error, and spread error.
``2_0``
    Consolidated feature set. The flat rolling template was replaced by the
    three-tier window scheme, per-feature ``HOME - AWAY`` columns gave way to
    hand-picked contrasts, team-identity one-hots and the always ``-110``
    normalized price columns were dropped, and the park, umpire, Statcast,
    bullpen and market-movement families were added. Availability also changed
    meaning: ``N_OBSERVED_ABSENT`` now counts hitters missing from the starting
    lineup, where it previously excused any hitter who later made a game
    appearance -- post-game information that had reached a ``_BEFORE`` column.
"""

