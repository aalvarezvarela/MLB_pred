"""Schema versions for generated MLB training datasets.

Increment a value whenever a regenerated CSV gains, loses, or redefines a
column. Versioned filenames keep older, checksum-pinned datasets intact.

History
-------
``1_0``
    First one-row-per-game dataset. Pregame features plus reproducible outcomes
    for total runs, home margin, total-line error and spread error, built on the
    three-tier rolling window scheme with hand-picked ``HOME - AWAY`` contrasts
    rather than a per-feature difference. Carries the closing-market, rolling
    team/market history, context, matchup, market-regime, availability, park,
    umpire, Statcast, bullpen, market-movement, roster-continuity and
    team-identity families.
"""

