#: Versioned independently of the per-game dataset: the two are generated by
#: different builders and either can gain a column without the other changing.
#: Both markets share this version, because one builder emits them and a schema
#: change touches both.
#:
#: ``1_0``
#:     First one-row-per-(game, snapshot) dataset. The market quote as of each
#:     pre-game horizon anchors the target, and the closing quote moves to a
#:     physically separate scoring sidecar. Availability, umpire and
#:     open-to-close movement are excluded because their publication time cannot
#:     be reconstructed at an arbitrary horizon; roster continuity and team
#:     identity are not, because identity is known as soon as the schedule is
#:     published and continuity is built from announced transactions read on
#:     ``known_date``.
